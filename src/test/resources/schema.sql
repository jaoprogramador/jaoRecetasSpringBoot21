DROP TABLE IF EXISTS recetas;
DROP TABLE IF EXISTS categorias;

CREATE TABLE categorias (
                            id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            nombre VARCHAR(50) NOT NULL,
                            procedencia VARCHAR(50) NOT NULL,
                            tipo_alimento VARCHAR(50) NOT NULL
);

CREATE TABLE recetas (
                         id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         categoria_id INT NOT NULL,
                         descripcion VARCHAR(500) NOT NULL,
                         fecha_alta TIMESTAMP NULL,
                         fecha_modificacion TIMESTAMP NULL,
                         ingredientes VARCHAR(255), -- Adaptado para que H2 lo lea bien en los tests
                         instrucciones VARCHAR(255) NULL,
                         porciones INT NULL,
                         tiempo_preparacion_minutos INT NULL,
                         titulo VARCHAR(200) NOT NULL,
                         activo VARCHAR(1) DEFAULT 'S' NULL,
                         CONSTRAINT fkm93h6wyu1wt19rrwa5b2doph2 FOREIGN KEY (categoria_id) REFERENCES categorias(id)
);